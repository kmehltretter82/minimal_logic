#!/usr/bin/env python3
"""Package proofs from Proofs/ as single-file prove2.me solutions in Solutions/.

prove2.me verifies one `solution.lean` per theorem. It may import Mathlib, platform
definitions and other platform theorems, but not this repository's own modules. This
script concatenates the needed Proofs/ modules (without their imports) and ends the file
with `theorem solution`, whose binders and type are copied verbatim from the published
statement in Theorems/.

Usage: python3 scripts/package_solutions.py
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent

PACKAGES = {
    "Schwichtenberg1976V2": {
        "import": "import Definitions.Def_Schwichtenberg1976V2_Lambda",
        "dir": "Proofs/Schwichtenberg1976V2",
        "targets": {
            "normal_subterm_structure": (
                ["Basic", "NormalSubterms"],
                "Fs α r hFs hα hr_ty hr_norm hr_fv"),
            "subterm_polynomial_lemma": (
                ["Basic", "Reduction", "SubtermPolynomial"],
                "k Fs α hFs_ty hFs_inj hα_ty s hs"),
            "combinators_and_sufficiency": (
                ["Basic", "Reduction", "NormalSubterms", "Combinators", "Sufficiency"],
                ""),
            "definable_iff_extended_polynomial": (
                ["Basic", "Reduction", "NormalSubterms", "Combinators", "Sufficiency",
                 "Piecewise", "Semantics", "Necessity", "MainTheorem"],
                "k f"),
        },
    },
}


def statement(ns: str, name: str) -> str:
    """The published statement, renamed to `solution`, without docstring or proof."""
    text = (ROOT / "Theorems" / f"Thm_{ns}_{name}.lean").read_text()
    body = text.split(f"namespace {ns}\n", 1)[1].rsplit(f"end {ns}", 1)[0]
    body = re.sub(r"/--.*?-/\s*", "", body, flags=re.S).strip()
    assert body.startswith(f"theorem {name}"), body[:80]
    body = "theorem solution" + body[len(f"theorem {name}"):]
    body = re.sub(r":=\s*by\s*sorry\s*$", "", body).rstrip()
    return body


def package(ns: str, spec: dict) -> None:
    for name, (modules, args) in spec["targets"].items():
        parts = [
            f"{spec['import']}\n",
            f"/-!\n# Solution: `{ns}.{name}`\n\n"
            f"Generated by `scripts/package_solutions.py` from the modules "
            f"{', '.join(modules)} in `{spec['dir']}`. Edit those modules, not this file.\n-/\n",
        ]
        for m in modules:
            src = (ROOT / spec["dir"] / f"{m}.lean").read_text()
            src = "\n".join(l for l in src.splitlines() if not l.startswith("import "))
            parts.append(f"\n-- ===== {spec['dir']}/{m}.lean =====\n{src.strip()}\n")
        call = f"{ns}.Proofs.{name}" + (f" {args}" if args else "")
        parts.append(f"\nopen {ns} in\n{statement(ns, name)} :=\n  {call}\n")
        out = ROOT / "Solutions" / f"Sol_{ns}_{name}.lean"
        out.write_text("".join(parts))
        print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    for ns, spec in PACKAGES.items():
        package(ns, spec)
